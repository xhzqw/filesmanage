#!/usr/bin/env python3
"""Extract the official cyan/blue mark from the white JPEG matte (stdlib only).

Accepts a 256px uncompressed 24-bit BMP generated by macOS sips.
Emits real RGBA PNG before downsizing, avoiding white edge halos.
"""
import struct
import sys
import zlib
from pathlib import Path


def convert(source: Path, target: Path) -> None:
    bmp = source.read_bytes()
    if bmp[:2] != b"BM":
        raise ValueError("Not a BMP")
    offset = struct.unpack_from("<I", bmp, 10)[0]
    width, signed_height = struct.unpack_from("<ii", bmp, 18)
    planes, depth = struct.unpack_from("<HH", bmp, 26)
    compressed = struct.unpack_from("<I", bmp, 30)[0]
    if (width, abs(signed_height), planes, depth, compressed) != (256, 256, 1, 24, 0):
        raise ValueError("Unexpected sips BMP layout")
    height = abs(signed_height)
    stride = (3 * width + 3) & ~3
    if len(bmp) < offset + height * stride:
        raise ValueError("Truncated BMP")
    raw = bytearray()
    visible = clear = 0
    for y in range(height):
        raw.append(0)  # PNG filter type 0
        source_y = y if signed_height < 0 else height - y - 1
        row = offset + source_y * stride
        for x in range(width):
            b, g, r = bmp[row + x * 3:row + x * 3 + 3]
            if b - r < 12 or g < r - 8:
                alpha = 0  # neutral JPEG whites are background
            elif r <= 32:
                alpha = 255
            else:
                alpha = max(0, min(255, round((255 - r) * 255 / 231)))
            if alpha == 0:
                raw.extend((0, 0, 0, 0))
                clear += 1
            elif alpha == 255:
                raw.extend((r, g, b, 255))
                visible += 1
            else:
                def unmatte(channel: int) -> int:
                    return max(0, min(255, round((channel * 255 - (255 - alpha) * 255) / alpha)))
                raw.extend((unmatte(r), unmatte(g), unmatte(b), alpha))
                visible += 1
    if visible < 1000 or clear < 1000:
        raise ValueError("No plausible logo or transparent background detected")

    def png_chunk(kind: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + kind + data
                + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff))
    target.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + png_chunk(b"IDAT", zlib.compress(raw, 9))
        + png_chunk(b"IEND", b"")
    )


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("Usage: favicon_alpha.py INPUT.bmp OUTPUT.png")
    convert(Path(sys.argv[1]), Path(sys.argv[2]))
